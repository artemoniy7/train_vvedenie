"""Настройки игры с отдельным режимом для устройств под Linux."""  # Общие параметры проекта.

import sys  # Нужен, чтобы определить операционную систему, на которой запущена игра.

IS_LINUX = sys.platform.startswith("linux")  # True, если игра запущена в Linux; иначе False.

BOARD_WIDTH = 10  # Ширина игрового поля в клетках.
BOARD_HEIGHT = 20  # Высота игрового поля в клетках.

if IS_LINUX:  # На Linux используем портретный экран устройства.
    WINDOW_WIDTH = 1224  # Ширина экрана Linux-устройства в пикселях.
    WINDOW_HEIGHT = 2720  # Высота экрана Linux-устройства в пикселях.
    CELL_SIZE = 80  # Размер клетки увеличен для удобной игры на сенсорном экране.
    BOARD_LEFT = (WINDOW_WIDTH - CELL_SIZE * BOARD_WIDTH) // 2  # Размещаем поле по центру по горизонтали.
    BOARD_TOP = 180  # Оставляем место сверху для заголовка и счёта.
else:  # На других операционных системах оставляем компактное окно для компьютера.
    CELL_SIZE = 30  # Размер клетки в пикселях.
    WINDOW_WIDTH = 620  # Ширина окна игры в пикселях.
    WINDOW_HEIGHT = 660  # Высота окна игры в пикселях.
    BOARD_LEFT = 40  # Отступ левого края поля от левого края окна.
    BOARD_TOP = 30  # Отступ верхнего края поля от верхнего края окна.

BOARD_PIXEL_WIDTH = CELL_SIZE * BOARD_WIDTH  # Ширина игрового поля в пикселях.
BOARD_PIXEL_HEIGHT = CELL_SIZE * BOARD_HEIGHT  # Высота игрового поля в пикселях.

FPS = 60  # Целевая частота обновления экрана — 60 кадров в секунду.
FALL_INTERVAL = 500  # Интервал между автоматическими шагами фигуры вниз, в миллисекундах.

BACKGROUND_COLOR = (18, 22, 32)  # Цвет фона окна в формате RGB.
BOARD_COLOR = (28, 34, 48)  # Цвет внутренней области игрового поля.
